#pragma once
#include <Arduino.h>

// Пассивный сниффер 1-Wire на D2 (INT0). Только слушает линию.
// Работает, пока ПК не пришлёт любой байт. Потоковые записи (байты 7-битные,
// заголовок записи — со старшим битом):
//   0x80|f  low   слот: f = бит0 «бит», бит1 «в окне был повторный спад»,
//                 бит2 «ноль держался до конца окна»; low — ноль, мкс (до 127)
//   0x90  lo hi  m0 m1 m2 m3   сброс: ноль (14 бит, мкс) + время от старта, мс (28 бит)
//   0x91  lo hi   импульс присутствия, мкс
//   0x92          после сброса присутствия нет
//   0x93  lo hi   ноль 120…380 мкс — не бит и не сброс, мкс
//   0x94  b0 b1 b2   высокий уровень дольше 1 мс, мкс (21 бит)
//   0x95  n       потеряно n событий захвата
//   0x96  lo hi   потеряно байт вывода
//   0x97  lvl     начало: уровень линии (1 — высокий)
//   0xFF          конец (после него идёт обычный ответ ST_OK)
// Байты хранятся младшими семёрками вперёд.
//
// evmem — не менее 160 байт (очередь фронтов), outmem — ровно 256 байт
// (кольцо вывода). Обе — чужие буферы, на время захвата они заняты.
void sniff_run(uint8_t *evmem, uint8_t *outmem);
